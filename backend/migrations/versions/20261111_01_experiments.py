"""Seed the simulated vial inventory and link readings to experiments."""

from alembic import op

revision = "20261111_01"
down_revision = "20261109_01"
branch_labels = None
depends_on = None


def upgrade() -> None:
    op.execute(
        """
        DO $$
        BEGIN
            IF EXISTS (SELECT 1 FROM vials) THEN
                RAISE EXCEPTION 'The experiment pilot needs an empty vial inventory';
            END IF;
        END $$;

        INSERT INTO vials (vial_id, equipment_id, label, created_at)
        SELECT slot, 'evolver-sim-01', 'Vial ' || slot, now()
        FROM generate_series(1, 12) AS slot;
        ALTER TABLE vials ALTER COLUMN vial_id RESTART WITH 13;

        CREATE TABLE experiments (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name varchar(120) NOT NULL,
            vial_id bigint NOT NULL REFERENCES vials(vial_id) ON DELETE RESTRICT,
            started_at timestamptz NOT NULL,
            ended_at timestamptz,
            deleted_at timestamptz,
            CONSTRAINT ck_experiment_interval CHECK (ended_at >= started_at),
            CONSTRAINT ck_experiment_deletion CHECK (
                deleted_at IS NULL OR (ended_at IS NOT NULL AND deleted_at >= ended_at)
            )
        );
        CREATE UNIQUE INDEX uq_experiments_active_vial
            ON experiments (vial_id) WHERE ended_at IS NULL;

        ALTER TABLE temperature_readings ADD COLUMN experiment_id bigint NOT NULL
            REFERENCES experiments(id) ON DELETE RESTRICT;
        CREATE INDEX ix_temperature_readings_experiment_time
            ON temperature_readings (experiment_id, generated_at);
        """
    )


def downgrade() -> None:
    raise RuntimeError("Downgrading would discard experiment history; restore a backup")
